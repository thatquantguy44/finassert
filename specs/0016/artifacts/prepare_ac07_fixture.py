"""Recreate the disposable AC-07 source with an existing sideload task pane.

Supply a workbook generated by Microsoft's Office add-in sideload tool, using
the registered local manifest. This copies its task-pane parts into synthetic
workbooks; it neither registers an add-in nor establishes native acceptance.
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import io
import json
import xml.etree.ElementTree as ET
from datetime import datetime
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile

from openpyxl import Workbook
from openpyxl.utils.datetime import CALENDAR_MAC_1904, CALENDAR_WINDOWS_1900

from finassert.policy.templates import get_template

TASKPANE_REL = "http://schemas.microsoft.com/office/2011/relationships/webextensiontaskpanes"
TYPE_NS = "http://schemas.openxmlformats.org/package/2006/content-types"


def prepare(destination: Path, sideload_seed: Path) -> dict:
    """Create two offset/date fixtures while preserving supplied task-pane parts."""
    if sideload_seed.resolve() in {
        (destination / f"ac07-{epoch}.xlsx").resolve() for epoch in ("1900", "1904")
    }:
        raise ValueError("The disposable output must not replace its sideload seed")
    seed_bytes = sideload_seed.read_bytes()
    with ZipFile(io.BytesIO(seed_bytes)) as seed:
        parts = {
            name: seed.read(name)
            for name in seed.namelist()
            if name.startswith("xl/webextensions/") and not name.endswith("/")
        }
        relationships = ET.fromstring(seed.read("_rels/.rels"))
        taskpanes = [item for item in relationships if item.get("Type") == TASKPANE_REL]
        if len(taskpanes) != 1 or taskpanes[0].get("Target", "").lstrip("/") not in parts:
            raise ValueError("Supply an Office-generated workbook with one task-pane relationship")
        overrides = [
            item
            for item in ET.fromstring(seed.read("[Content_Types].xml"))
            if item.tag == f"{{{TYPE_NS}}}Override"
            and item.get("PartName", "").lstrip("/") in parts
        ]
        if not any(
            item.get("ContentType") == "application/vnd.ms-office.webextension+xml"
            for item in overrides
        ):
            raise ValueError("Sideload workbook is missing its task-pane parts or content types")

    destination.mkdir(parents=True, exist_ok=True)
    files = []
    for epoch, calendar in (("1900", CALENDAR_WINDOWS_1900), ("1904", CALENDAR_MAC_1904)):
        book = Workbook()
        book.epoch = calendar
        sheet = book.active
        sheet.title = "Sheet1"
        rows = [
            ["portfolio", "ticker", "weight", "market_value", "nav", "date"],
            ["Alpha", "AAA", 0.4, -400, 1000, datetime(2026, 1, 1)],
            ["Alpha", "BBB", 0.6, 600, 1000, datetime(2026, 1, 1)],
        ]
        for row_index, row in enumerate(rows, 7):
            for column_index, value in enumerate(row, 3):
                sheet.cell(row_index, column_index, value)
        for row_index in (8, 9):
            sheet.cell(row_index, 5).number_format = "0.0%"
            sheet.cell(row_index, 8).number_format = "yyyy-mm-dd"
        for column in "CDEFGH":
            sheet.column_dimensions[column].width = 20
        sheet.sheet_view.selection[0].activeCell = "C7"
        sheet.sheet_view.selection[0].sqref = "C7:H9"
        buffer = io.BytesIO()
        book.save(buffer)
        book.close()
        with ZipFile(buffer) as plain:
            contents = {name: plain.read(name) for name in plain.namelist()}
        root_rels = ET.fromstring(contents["_rels/.rels"])
        relationship = copy.deepcopy(taskpanes[0])
        relationship.set("Id", "rIdFinassertTaskpane")
        root_rels.append(relationship)
        contents["_rels/.rels"] = ET.tostring(root_rels, encoding="utf-8", xml_declaration=True)
        content_types = ET.fromstring(contents["[Content_Types].xml"])
        content_types.extend(copy.deepcopy(overrides))
        contents["[Content_Types].xml"] = ET.tostring(
            content_types, encoding="utf-8", xml_declaration=True
        )
        contents.update(parts)
        path = destination / f"ac07-{epoch}.xlsx"
        with ZipFile(path, "w", compression=ZIP_DEFLATED) as output:
            for name, data in contents.items():
                output.writestr(name, data)
        files.append(path)

    policy = destination / "long-only-holdings.yml"
    policy.write_text(get_template("long-only-holdings").to_yaml(), encoding="utf-8")
    files.append(policy)
    identities = {
        "scope": "Synthetic setup only; native correction/export acceptance must be observed",
        "sideload_seed_sha256": hashlib.sha256(seed_bytes).hexdigest(),
        "source": "Sheet1!C7:H9",
        "correction": "F8: -400 to 400",
        "files_sha256": {
            path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in files
        },
    }
    (destination / "identities.json").write_text(
        json.dumps(identities, indent=2) + "\n", encoding="utf-8"
    )
    return identities


def main() -> None:
    """Prepare only explicitly named disposable files; never discover user workbooks."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("destination", type=Path)
    parser.add_argument("--sideload-seed", type=Path, required=True)
    arguments = parser.parse_args()
    print(json.dumps(prepare(arguments.destination, arguments.sideload_seed), indent=2))


if __name__ == "__main__":
    main()
